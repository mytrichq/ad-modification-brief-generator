const esc = (s) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
const FIELD_LABEL = { visual: 'Visual', voiceover: 'Voiceover', on_screen_text: 'On-screen text' };
const TYPE_LABEL = { hook: 'Hook', recut: 'Re-cut', revoice: 'Re-voice', ending: 'Ending', new_angle: 'New angle', new_creator: 'New creator' };
const METRIC = { hook_rate: 'hook rate', ctr: 'CTR', cpa: 'CPA', completion_rate: 'completion rate' };
export function selectMods(run, only = 'auto') {
  const mods = run.mods?.mods || [];
  const approved = mods.filter((m) => run.reviews[m.mod_id]?.verdict === 'approve');
  if (only === 'approved' || (only === 'auto' && approved.length)) return { mods: approved, label: 'approved' };
  if (only === 'passed') {
    const ok = new Set(run.check.results.filter((r) => r.status !== 'fail').map((r) => r.mod_id));
    return { mods: mods.filter((m) => ok.has(m.mod_id)), label: 'passed QA' };
  }
  return { mods, label: 'all' };
}

const resultOf = (run, modId) => run.check?.results.find((r) => r.mod_id === modId) || { changes: [], issues: [], status: 'unchecked' };
export function toMarkdown(run, only) {
  const { mods, label } = selectMods(run, only);
  const locked = run.dna.elements.filter((e) => e.lock);
  const out = [
    `# Modification briefs: ${run.meta.creative_id} "${run.script.title}"`,
    '',
    `Run ${run.id} · ${plural(mods.length, 'modification')} (${label}) · generated by ${run.mods.provider}`,
    '',
    `**Why it works:** ${run.dna.summary}`,
    '',
    '**Keep as is in every modification:**',
    ...locked.map((e) => `- Scene ${e.scene}, ${FIELD_LABEL[e.field]}: "${cellText(run.script, e.scene, e.field)}"`),
    '',
  ];
  for (const m of mods) {
    const r = resultOf(run, m.mod_id);
    const review = run.reviews[m.mod_id];
    out.push(
      `## ${m.mod_id} · ${TYPE_LABEL[m.mod_type]} · ${m.title}`,
      '',
      `${r.production ? `Production: **${effortText(r.production)}** · ` : ''}QA: **${r.status}**${review ? ` · Review: **${review.verdict}**${review.reason ? ` (${review.reason})` : ''}` : ''}`,
      '',
      `**Hypothesis:** ${m.hypothesis}${m.read_metric ? ` _(read on ${METRIC[m.read_metric] || m.read_metric})_` : ''}`,
      '',
      ...(directionRows(m.direction).length ? [`**Direction:** ${directionRows(m.direction).map(([k, v]) => `${k}: ${v}`).join(' · ')}`, ''] : []),
      ...(m.scenes.some((x) => x.footage) ? [`**Footage:** ${m.scenes.map((x) => `S${x.scene} ${x.footage || 'reuse'}`).join(', ')}`, ''] : []),
      '**What changes:**',
      '',
      '| Scene | Field | Before | After |',
      '|---|---|---|---|',
      ...r.changes.map((c) => `| ${c.scene} | ${FIELD_LABEL[c.field]} | ${c.before ?? '(new)'} | ${c.after ?? '(cut)'} |`),
      '',
      '**Full script:**',
      '',
      scriptToMarkdown(m),
      '',
      ...(r.issues.length ? ['**QA notes:**', ...r.issues.map((i) => `- ${i.severity}: ${i.message}`), ''] : []),
    );
  }
  return out.join('\n');
}
export function toCsvRows(run, only) {
  const { mods } = selectMods(run, only);
  return toCsv(mods.map((m) => {
    const r = resultOf(run, m.mod_id);
    return {
      mod_id: m.mod_id,
      parent_id: m.parent_id,
      mod_type: m.mod_type,
      title: m.title,
      hypothesis: m.hypothesis,
      what_changes: r.changes.map((c) => `S${c.scene} ${c.field}: ${c.after ?? '(cut)'}`).join(' | '),
      production: r.production ? effortText(r.production) : '',
      read_on: m.read_metric || '',
      direction: directionRows(m.direction).map(([k, v]) => `${k}: ${v}`).join(' | '),
      qa_status: r.status,
      qa_notes: r.issues.map((i) => i.message).join(' | '),
      review: run.reviews[m.mod_id]?.verdict || '',
      review_note: run.reviews[m.mod_id]?.reason || '',
      voiceover: m.scenes.map((s) => s.voiceover).join(' '),
      on_screen_text: m.scenes.map((s) => s.on_screen_text).join(' / '),
    };
  }), undefined, { safe: true });
}
const FIELD_SHORT = { visual: 'Visual', voiceover: 'Voiceover', on_screen_text: 'On-screen' };
const FIELD_ORDER = { voiceover: 0, on_screen_text: 1, visual: 2 };

function keptScenes(run) {
  return run.script.scenes.map((s) => s.scene).filter((n) => {
    const els = run.dna.elements.filter((e) => e.scene === n);
    return els.length && els.every((e) => e.lock);
  });
}
function rangeText(ns) {
  const out = [];
  let a = ns[0], p = ns[0];
  for (const n of [...ns.slice(1), null]) {
    if (n === p + 1) { p = n; continue; }
    out.push(a === p ? `${a}` : `${a}–${p}`);
    a = p = n;
  }
  return out.join(', ');
}

const plural = (n, one, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;
const LEVEL = { light: 'Light', medium: 'Medium', heavy: 'Heavy' };
export const effortText = (p) => `${LEVEL[p.level]} · ${p.tasks.join(', ') || 'small edit'}${p.total ? ` · ${p.reused}/${p.total} scenes from existing footage` : ''}`;
const directionRows = (d) => [['Talent', d?.talent], ['Location', d?.location], ['Voice', d?.voice], ['Music', d?.music], ['Captions', d?.captions]]
  .filter(([, v]) => v && !/^same as (the )?original\.?$/i.test(String(v).trim()));

function changeGrid(m, r) {
  const cut = new Set(r.changes.filter((c) => c.after === null).map((c) => c.scene));
  const foot = (n) => m.scenes.find((s) => s.scene === n)?.footage;
  const rows = [
    ...r.changes.filter((c) => !cut.has(c.scene)).map((c) => [c.scene, FIELD_ORDER[c.field],
      `<span class="k">S${c.scene} · ${FIELD_SHORT[c.field]}${c.field === 'visual' && foot(c.scene) === 'new' ? ' · new shot' : ''}</span><span class="v ${c.field === 'visual' ? 'visual' : ''}">${esc(c.after)}</span>`]),
    ...[...cut].map((n) => [n, 0, `<span class="k">S${n} · Whole scene</span><span class="v cut">Cut</span>`]),
  ].sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  return `<div class="grid">${rows.map((x) => x[2]).join('')}</div>`;
}

function briefSection(run, m, { compact = false } = {}) {
  const r = resultOf(run, m.mod_id);
  const review = run.reviews[m.mod_id];
  const notes = r.issues.map((i) => `<span class="${i.severity === 'error' ? 'fail' : 'warn'}">${esc(i.message)}</span>`).join('');
  const dir = directionRows(m.direction);
  return `<${compact ? 'div class="stack-item"' : 'section'}>
    <div class="sh"><${compact ? 'h3' : 'h2'}>${esc(m.title)}</${compact ? 'h3' : 'h2'}><span class="mono">${esc(m.mod_id.split('-').pop())}${compact ? '' : ` · ${esc(TYPE_LABEL[m.mod_type] || m.mod_type)}`}${m.read_metric ? ` · read on ${esc(METRIC[m.read_metric] || m.read_metric)}` : ''}</span></div>
    ${r.production ? `<p class="effort ${r.production.level}">${esc(effortText(r.production))}</p>` : ''}
    ${compact ? '' : `<p class="hyp">${esc(m.hypothesis)}</p>`}
    ${notes ? `<div class="notes">${notes}</div>` : ''}
    ${dir.length ? `<dl class="dir">${dir.map(([k, v]) => `<dt>${k}</dt><dd>${esc(v)}</dd>`).join('')}</dl>` : ''}
    ${changeGrid(m, r)}
    ${review?.reason ? `<p class="reason">Reviewer: “${esc(review.reason)}”</p>` : ''}
  </${compact ? 'div' : 'section'}>`;
}
function briefBody(run, mods) {
  const hooks = mods.filter((m) => m.mod_type === 'hook');
  if (hooks.length < 2) return mods.map((m) => briefSection(run, m)).join('');
  const touched = new Set(hooks.flatMap((m) => resultOf(run, m.mod_id).changes.map((c) => c.scene)));
  const body = run.script.scenes.map((s) => s.scene).filter((n) => !touched.has(n));
  const stack = `<section><div class="sh"><h2>Hook stack · ${plural(hooks.length, 'opening')}</h2><span class="mono">one edit session</span></div>
    <p class="hyp">Build the body once${body.length ? ` (scene${body.length > 1 ? 's' : ''} ${rangeText(body)} from the original edit)` : ''}, then export one ad per opening.</p>
    ${hooks.map((m) => briefSection(run, m, { compact: true })).join('')}</section>`;
  return stack + mods.filter((m) => m.mod_type !== 'hook').map((m) => briefSection(run, m)).join('');
}

