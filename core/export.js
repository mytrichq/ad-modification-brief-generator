function findChrome() {
  const candidates = [
    process.env.CHROME_PATH,
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    '/Applications/Chromium.app/Contents/MacOS/Chromium',
    '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge',
    'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',
  ].filter(Boolean);
  for (const c of candidates) if (existsSync(c)) return c;
  for (const bin of ['google-chrome', 'chromium', 'chromium-browser', 'microsoft-edge']) {
    const r = spawnSync('which', [bin], { encoding: 'utf8' });
    if (r.status === 0) return r.stdout.trim();
  }
  return null;
}

export function htmlToPdf(htmlFile, pdfFile) {
  const chrome = findChrome();
  if (!chrome) return { ok: false, reason: 'Chrome/Chromium not found (set CHROME_PATH). Open the HTML file and use Print → Save as PDF.' };
  const r = spawnSync(chrome, ['--headless=new', '--disable-gpu', '--no-pdf-header-footer', `--print-to-pdf=${pdfFile}`, pathToFileURL(htmlFile).href], { timeout: 60_000, encoding: 'utf8' });
  return existsSync(pdfFile) ? { ok: true } : { ok: false, reason: `Chrome could not print the PDF. ${r.stderr?.slice(0, 300) || ''}` };
}

export function exportRun(run, { formats = ['md', 'csv', 'html', 'pdf'], only = 'auto', outDir } = {}) {
  if (!run.mods || !run.check) throw new Error('Nothing to export yet: generate modifications first.');
  const dir = outDir || path.join(run.dir, 'export');
  mkdirSync(dir, { recursive: true });
  const base = path.join(dir, `briefs-${run.meta.creative_id}`);
  const files = {};
  const notes = [];
  if (formats.includes('md')) writeFileSync((files.md = `${base}.md`), toMarkdown(run, only));
  if (formats.includes('csv')) writeFileSync((files.csv = `${base}.csv`), toCsvRows(run, only));
  if (formats.includes('html') || formats.includes('pdf')) writeFileSync((files.html = `${base}.html`), toHtml(run, only));
  if (formats.includes('pdf')) {
    const r = htmlToPdf(files.html, `${base}.pdf`);
    if (r.ok) files.pdf = `${base}.pdf`;
    else notes.push(r.reason);
  }
  return { files, notes, selection: selectMods(run, only) };
}
